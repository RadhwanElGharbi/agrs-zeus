ProjectConfig ProjectConfig::load_from_yaml(const std::string& yaml_path) {
    ProjectConfig config;
    
    std::cout << "📖 Loading project configuration from: " << yaml_path << std::endl;
    
    std::ifstream file(yaml_path);
    if (!file.is_open()) {
        std::cerr << "❌ Failed to open config file: " << yaml_path << std::endl;
        return config;
    }
    
    // Simple YAML parser (for basic key-value pairs)
    // TODO: Use a proper YAML library (yaml-cpp) for production
    std::string line;
    while (std::getline(file, line)) {
        // Skip comments and empty lines
        if (line.empty() || line[0] == '#') continue;
        
        // Find key-value separator
        size_t colon_pos = line.find(':');
        if (colon_pos == std::string::npos) continue;
        
        std::string key = line.substr(0, colon_pos);
        std::string value = line.substr(colon_pos + 1);
        
        // Trim whitespace
        key.erase(0, key.find_first_not_of(" \t"));
        key.erase(key.find_last_not_of(" \t") + 1);
        value.erase(0, value.find_first_not_of(" \t"));
        value.erase(value.find_last_not_of(" \t") + 1);
        
        // Parse basic fields
        if (key == "project_name") {
            config.project_name = value;
        } else if (key == "project_code") {
            config.project_code = value;
        } else if (key == "client_name") {
            config.client_name = value;
        } else if (key == "epsg_code") {
            config.epsg_code = std::stoi(value);
        } else if (key == "measurement_units") {
            config.measurement_units = value;
        } else if (key == "start_x") {
            config.start_point.x = std::stod(value);
        } else if (key == "start_y") {
            config.start_point.y = std::stod(value);
        } else if (key == "end_x") {
            config.end_point.x = std::stod(value);
        } else if (key == "end_y") {
            config.end_point.y = std::stod(value);
        } else if (key == "project_dir") {
            config.project_dir = value;
        } else if (key == "max_slope_percent") {
            config.constraints.max_slope_percent = std::stod(value);
        } else if (key == "learning_rate") {
            config.training.learning_rate = std::stod(value);
        }
        // Add more fields as needed...
    }
    
    std::cout << "✅ Configuration loaded: " << config.project_name << std::endl;
    
    return config;
}

