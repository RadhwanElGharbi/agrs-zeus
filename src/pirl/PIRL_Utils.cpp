std::vector<ProjectConfig> generate_training_scenarios(
    const std::string& base_config_path,
    int num_easy,
    int num_medium,
    int num_hard) {
    
    std::cout << "🎓 Generating training scenarios..." << std::endl;
    std::cout << "  Easy: " << num_easy << std::endl;
    std::cout << "  Medium: " << num_medium << std::endl;
    std::cout << "  Hard: " << num_hard << std::endl;
    
    std::vector<ProjectConfig> scenarios;
    
    // Load base configuration
    ProjectConfig base = ProjectConfig::load_from_yaml(base_config_path);
    
    std::random_device rd;
    std::mt19937 gen(rd());
    
    // Generate easy scenarios (flat terrain, no obstacles)
    for (int i = 0; i < num_easy; ++i) {
        ProjectConfig config = base;
        config.project_name = "training_easy_" + std::to_string(i);
        
        // Short distance, flat terrain assumptions
        std::uniform_real_distribution<> dist_short(1000.0, 5000.0);
        double distance = dist_short(gen);
        
        config.end_point.x = config.start_point.x + distance;
        config.end_point.y = config.start_point.y;
        
        scenarios.push_back(config);
    }
    
    // Generate medium scenarios (moderate terrain, some obstacles)
    for (int i = 0; i < num_medium; ++i) {
        ProjectConfig config = base;
        config.project_name = "training_medium_" + std::to_string(i);
        
        // Medium distance, varied direction
        std::uniform_real_distribution<> dist_medium(5000.0, 20000.0);
        std::uniform_real_distribution<> angle(-M_PI, M_PI);
        
        double distance = dist_medium(gen);
        double theta = angle(gen);
        
        config.end_point.x = config.start_point.x + distance * std::cos(theta);
        config.end_point.y = config.start_point.y + distance * std::sin(theta);
        
        scenarios.push_back(config);
    }
    
    // Generate hard scenarios (long distance, complex terrain)
    for (int i = 0; i < num_hard; ++i) {
        ProjectConfig config = base;
        config.project_name = "training_hard_" + std::to_string(i);
        
        // Long distance, complex routing
        std::uniform_real_distribution<> dist_long(20000.0, 100000.0);
        std::uniform_real_distribution<> angle(-M_PI, M_PI);
        
        double distance = dist_long(gen);
        double theta = angle(gen);
        
        config.end_point.x = config.start_point.x + distance * std::cos(theta);
        config.end_point.y = config.start_point.y + distance * std::sin(theta);
        
        // Tighter constraints for hard scenarios
        config.constraints.max_slope_percent = 20.0; // Stricter
        
        scenarios.push_back(config);
    }
    
    std::cout << "✅ Generated " << scenarios.size() << " training scenarios" << std::endl;
    
    return scenarios;
}

void create_synthetic_projects(const std::string& output_dir, int num_projects) {
    std::cout << "🏗️  Creating " << num_projects << " synthetic projects..." << std::endl;
    
    // Create output directory
    std::filesystem::create_directories(output_dir);
    
    std::random_device rd;
    std::mt19937 gen(rd());
    std::uniform_real_distribution<> coord(300000.0, 700000.0);
    
    for (int i = 0; i < num_projects; ++i) {
        std::string project_name = "synthetic_project_" + std::to_string(i);
        std::string project_dir = output_dir + "/" + project_name;
        
        std::filesystem::create_directories(project_dir);
        
        // Create basic project config
        ProjectConfig config;
        config.project_name = project_name;
        config.project_code = "SYN_" + std::to_string(i);
        config.client_name = "Synthetic";
        config.epsg_code = 32633; // UTM 33N
        config.measurement_units = "SI";
        
        // Random start/end points
        config.start_point.x = coord(gen);
        config.start_point.y = coord(gen);
        config.end_point.x = coord(gen);
        config.end_point.y = coord(gen);
        
        config.project_dir = project_dir;
        
        // Save config
        config.save_to_yaml(project_dir + "/project_config.yaml");
        
        if ((i + 1) % 10 == 0) {
            std::cout << "  Created " << (i + 1) << "/" << num_projects << " projects" << std::endl;
        }
    }
    
    std::cout << "✅ Synthetic projects created in: " << output_dir << std::endl;
}

