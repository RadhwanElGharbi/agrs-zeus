void export_to_geojson(const std::vector<std::pair<double, double>>& route,
                      const std::string& output_path,
                      int epsg_code) {
    std::ofstream out(output_path);
    if (!out.is_open()) {
        std::cerr << "❌ Failed to open output file: " << output_path << std::endl;
        return;
    }
    
    out << "{\n";
    out << "  \"type\": \"Feature\",\n";
    out << "  \"crs\": {\n";
    out << "    \"type\": \"name\",\n";
    out << "    \"properties\": {\n";
    out << "      \"name\": \"EPSG:" << epsg_code << "\"\n";
    out << "    }\n";
    out << "  },\n";
    out << "  \"properties\": {\n";
    out << "    \"route_type\": \"PIRL_optimized\",\n";
    out << "    \"num_points\": " << route.size() << "\n";
    out << "  },\n";
    out << "  \"geometry\": {\n";
    out << "    \"type\": \"LineString\",\n";
    out << "    \"coordinates\": [\n";
    
    for (size_t i = 0; i < route.size(); ++i) {
        out << "      [" << route[i].first << ", " << route[i].second << "]";
        if (i < route.size() - 1) out << ",";
        out << "\n";
    }
    
    out << "    ]\n";
    out << "  }\n";
    out << "}\n";
    
    out.close();
    std::cout << "✅ Route exported to GeoJSON: " << output_path << std::endl;
}

void export_to_shapefile(const std::vector<std::pair<double, double>>& route,
                        const std::string& output_path,
                        int epsg_code) {
    GDALAllRegister();
    
    // Create shapefile
    GDALDriver* driver = GetGDALDriverManager()->GetDriverByName("ESRI Shapefile");
    if (!driver) {
        std::cerr << "❌ Shapefile driver not available" << std::endl;
        return;
    }
    
    GDALDataset* dataset = driver->Create(output_path.c_str(), 0, 0, 0, GDT_Unknown, nullptr);
    if (!dataset) {
        std::cerr << "❌ Failed to create shapefile: " << output_path << std::endl;
        return;
    }
    
    // Create spatial reference
    OGRSpatialReference srs;
    srs.importFromEPSG(epsg_code);
    
    // Create layer
    OGRLayer* layer = dataset->CreateLayer("route", &srs, wkbLineString, nullptr);
    if (!layer) {
        std::cerr << "❌ Failed to create layer" << std::endl;
        GDALClose(dataset);
        return;
    }
    
    // Add fields
    OGRFieldDefn field_type("route_type", OFTString);
    field_type.SetWidth(50);
    layer->CreateField(&field_type);
    
    OGRFieldDefn field_length("length_m", OFTReal);
    layer->CreateField(&field_length);
    
    // Create feature
    OGRFeature* feature = OGRFeature::CreateFeature(layer->GetLayerDefn());
    feature->SetField("route_type", "PIRL_optimized");
    
    // Create linestring geometry
    OGRLineString linestring;
    double total_length = 0.0;
    
    for (size_t i = 0; i < route.size(); ++i) {
        linestring.addPoint(route[i].first, route[i].second);
        
        if (i > 0) {
            double dx = route[i].first - route[i-1].first;
            double dy = route[i].second - route[i-1].second;
            total_length += std::sqrt(dx*dx + dy*dy);
        }
    }
    
    feature->SetField("length_m", total_length);
    feature->SetGeometry(&linestring);
    
    // Save feature
    if (layer->CreateFeature(feature) != OGRERR_NONE) {
        std::cerr << "❌ Failed to create feature" << std::endl;
    }
    
    OGRFeature::DestroyFeature(feature);
    GDALClose(dataset);
    
    std::cout << "✅ Route exported to Shapefile: " << output_path << std::endl;
}

